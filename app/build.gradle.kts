/**
 * Release signing reads `keystore.properties` at the project root (never committed).
 * Without it the release build is produced unsigned.
 */
val keystoreProperties = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

android {
    namespace = "com.example.recipes"
    compileSdk = 37

    defaultConfig {
        applicationId = "io.github.donuriello.ricettario"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystoreProperties.containsKey("storeFile")) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            // Installs next to the release app instead of replacing it.
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            // Not minified until the release build has been checked on a device:
            // the app is small, and R8 problems would only show up at run time.
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    testOptions {
        unitTests {
            isIncludeAndroidResources = true
        }
    }
}

/**
 * Robolectric normally downloads its Android runtime jar at test time, outside Gradle.
 * Resolving it as a Gradle dependency gives caching and retries, and lets the tests run offline.
 */
val robolectricAndroidRuntime: Configuration by configurations.creating

tasks.withType<Test>().configureEach {
    val runtimeFiles: FileCollection = files(robolectricAndroidRuntime)
    inputs.files(runtimeFiles)
    jvmArgumentProviders.add(
        CommandLineArgumentProvider {
            listOf(
                "-Drobolectric.offline=true",
                "-Drobolectric.dependency.dir=${runtimeFiles.singleFile.parentFile.absolutePath}",
            )
        },
    )
}

